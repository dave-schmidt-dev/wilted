# Minimal authenticated client (stands in for the iPhone/native client)
# ---------------------------------------------------------------------------


class SpikeClient:
    """A minimal authenticated HTTPS client for this spike's protocol."""

    def __init__(self, host: str, port: int, ssl_context: ssl.SSLContext, holder_id: str) -> None:
        self.host = host
        self.port = port
        self._ssl_context = ssl_context
        self.holder_id = holder_id
        self._credential: bytes | None = None

    def enroll(self, token: str) -> bool:
        conn = http.client.HTTPSConnection(self.host, self.port, context=self._ssl_context, timeout=5)
        try:
            body = json.dumps({"token": token, "holder_id": self.holder_id}).encode()
            conn.request("POST", "/enroll", body=body, headers={"Content-Type": "application/json"})
            resp = conn.getresponse()
            data = json.loads(resp.read())
            if resp.status != 200:
                return False
            self._credential = bytes.fromhex(data["credential_hex"])
            return True
        finally:
            conn.close()

    def _authenticated_get(self, path: str, expected_revision: int = -1) -> http.client.HTTPResponse:
        conn = http.client.HTTPSConnection(self.host, self.port, context=self._ssl_context, timeout=5)
        headers = self._auth_headers("GET", path, expected_revision)
        conn.request("GET", path, headers=headers)
        return conn.getresponse()

    def _auth_headers(self, method: str, path: str, expected_revision: int) -> dict[str, str]:
        if self._credential is None:
            # Unauthenticated caller: send garbage/absent auth headers on
            # purpose, to exercise the AUTHENTICATED TRANSPORT rejection
            # path from the client side.
            return {}
        timestamp = f"{time.time():.6f}"
        nonce = uuid.uuid4().hex
        signature = _sign(self._credential, method, path, expected_revision, timestamp, nonce)
        return {
            "X-Holder-Id": self.holder_id,
            "X-Timestamp": timestamp,
            "X-Nonce": nonce,
            "X-Expected-Revision": str(expected_revision),
            "X-Signature": signature,
        }

    def fetch_manifest(self, expected_revision: int) -> tuple[int, bytes]:
        resp = self._authenticated_get(f"/manifest?expected_revision={expected_revision}", expected_revision)
        return resp.status, resp.read()

    def fetch_asset(self, expected_sha256: str, expected_revision: int = 1) -> tuple[int, bytes]:
        resp = self._authenticated_get(f"/asset?expected_sha256={expected_sha256}", expected_revision)
        return resp.status, resp.read()


