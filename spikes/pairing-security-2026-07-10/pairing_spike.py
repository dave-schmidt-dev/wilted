@dataclass
class PropertyResult:
    name: str
    passed: bool
    detail: str


def _free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


def run_spike(temp_dir: Path) -> list[PropertyResult]:
    """Run the full pairing/transport spike and return per-property results."""
    results: list[PropertyResult] = []

    key_path, cert_path = generate_ephemeral_tls_identity(temp_dir)

    manifest, asset = build_fixture_manifest_and_asset()
    pairing_store = PairingStore(temp_dir)

    server_ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    server_ctx.load_cert_chain(certfile=str(cert_path), keyfile=str(key_path))

    port = _free_port()
    httpd = _StationHTTPServer(("127.0.0.1", port), pairing_store, manifest, asset)
    httpd.socket = server_ctx.wrap_socket(httpd.socket, server_side=True)

    server_thread = threading.Thread(target=httpd.serve_forever, daemon=True)
    server_thread.start()
    try:
        client_ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
        # Certificate verification stays ON (CERT_REQUIRED is
        # PROTOCOL_TLS_CLIENT's default and is asserted explicitly below,
        # never weakened to CERT_NONE): trust is pinned to exactly this
        # run's ephemeral self-signed cert via load_verify_locations, so
        # any connection presenting a different certificate is rejected.
        # Only hostname matching is skipped, because this spike connects
        # to a literal loopback IP, not the cert's CN
        # ("wilted-station-spike.local") — that is a hostname-match
        # concern, not a trust concern, and is orthogonal to
        # verify_mode/CERT_REQUIRED.
        client_ctx.load_verify_locations(cafile=str(cert_path))
        client_ctx.verify_mode = ssl.CERT_REQUIRED
        client_ctx.check_hostname = False

        # -- Property 1: ONE-TIME ENROLLMENT ---------------------------------
        phone = SpikeClient("127.0.0.1", port, client_ctx, holder_id="iphone-spike")
        first_enroll_ok = phone.enroll(pairing_store.pairing_token)
        attacker_replay = SpikeClient("127.0.0.1", port, client_ctx, holder_id="attacker-replay")
        second_enroll_ok = attacker_replay.enroll(pairing_store.pairing_token)
        one_time_enrollment_ok = first_enroll_ok is True and second_enroll_ok is False
        results.append(
            PropertyResult(
                "ONE-TIME ENROLLMENT",
                one_time_enrollment_ok,
                f"first_enroll={first_enroll_ok} second_enroll_with_same_token={second_enroll_ok} "
                "(expected True, False)",
            )
        )

        # -- Property 2: AUTHENTICATED TRANSPORT -----------------------------
        unauthenticated = SpikeClient("127.0.0.1", port, client_ctx, holder_id="unpaired-client")
        status_unauth, body_unauth = unauthenticated.fetch_manifest(expected_revision=1)
        status_auth, body_auth = phone.fetch_manifest(expected_revision=1)
        authenticated_transport_ok = (
            status_unauth == 403 and body_unauth == b"" and status_auth == 200 and json.loads(body_auth)
        )
        results.append(
            PropertyResult(
                "AUTHENTICATED TRANSPORT",
                bool(authenticated_transport_ok),
                f"unauthenticated -> status={status_unauth} body_len={len(body_unauth)} (expected 403, 0 bytes); "
                f"authenticated -> status={status_auth} (expected 200 with manifest body)",
            )
        )

        # -- Property 3: STALE-REVISION REJECTION ----------------------------
        status_stale, body_stale = phone.fetch_manifest(expected_revision=0)  # current revision is 1
        status_current, _ = phone.fetch_manifest(expected_revision=1)
        stale_revision_ok = status_stale == 409 and status_current == 200
        results.append(
            PropertyResult(
                "STALE-REVISION REJECTION",
                stale_revision_ok,
                f"stale request (expected_revision=0 < current=1) -> status={status_stale} (expected 409); "
                f"current-revision request -> status={status_current} (expected 200)",
            )
        )

        # -- Property 4: ASSET-HASH REJECTION ---------------------------------
        tampered_hash = "0" * 64
        status_tampered, body_tampered = phone.fetch_asset(tampered_hash)
        status_valid, body_valid = phone.fetch_asset(asset.sha256)
        asset_hash_ok = (
            status_tampered == 409
            and body_tampered != asset.content
            and status_valid == 200
            and body_valid == asset.content
        )
        results.append(
            PropertyResult(
                "ASSET-HASH REJECTION",
                asset_hash_ok,
                f"tampered hash -> status={status_tampered} (expected 409, no asset bytes); "
                f"correct hash -> status={status_valid} bytes_match={body_valid == asset.content} (expected 200, True)",
            )
        )

        return results, pairing_store  # type: ignore[return-value]
    finally:
        httpd.shutdown()
        httpd.server_close()
        server_thread.join(timeout=5)


def assert_no_secret_leak(secret_values: list[str], captured_stdio: str) -> PropertyResult:
    """Grep-scan the repo tree and captured stdio for any generated secret substring.

    Args:
        secret_values: Every secret string/hex-encoded value this run
            generated (pairing token, per-client credentials).
        captured_stdio: Everything this script itself printed to
            stdout/stderr during the run (captured by ``main()``).

    Returns:
        A :class:`PropertyResult` — FAILS loudly (never prints the actual
        secret value in its detail message) if any secret substring is
        found anywhere it must not be.
    """
    problems: list[str] = []

    for value in secret_values:
        if not value:
            continue
        if value in captured_stdio:
            problems.append("a generated secret value was found in this script's own stdout/stderr")
            break

    # Scan every tracked-looking file under the repo working tree (source,
    # docs, config — anything that isn't inside the ephemeral temp dir,
    # which lives outside REPO_ROOT under the OS temp root).
    text_suffixes = {".py", ".md", ".toml", ".json", ".txt", ".cfg", ".ini", ".yaml", ".yml", ".log"}
    for path in REPO_ROOT.rglob("*"):
        if not path.is_file():
            continue
        if path.suffix not in text_suffixes:
            continue
        # Skip virtualenvs/build artifacts/VCS internals — never secret
        # material, and scanning them is slow and irrelevant.
        parts = set(path.parts)
        if parts & {".venv", ".git", "build", "__pycache__", ".pytest_cache", ".ruff_cache"}:
            continue
        try:
            contents = path.read_text(errors="ignore")
        except OSError:
            continue
        for value in secret_values:
            if value and value in contents:
                problems.append(f"a generated secret value was found in repo file: {path.relative_to(REPO_ROOT)}")

    if problems:
        return PropertyResult("SECRET HYGIENE", False, "; ".join(problems))
    return PropertyResult(
        "SECRET HYGIENE",
        True,
        f"scanned {len(secret_values)} generated secret value(s) against this script's own stdio output "
        f"and every text file under {REPO_ROOT} — none found outside the ephemeral temp dir",
    )


def main() -> int:
    temp_dir = Path(tempfile.mkdtemp(prefix="wilted-pairing-spike-"))
    results: list[PropertyResult] = []
    secret_values: list[str] = []
    try:
        run_output, pairing_store = run_spike(temp_dir)
        results.extend(run_output)
        secret_values = pairing_store.all_secret_values()
    except Exception as exc:  # noqa: BLE001 - a spike-infrastructure failure is itself a FAIL row
        results.append(PropertyResult("SPIKE EXECUTION", False, f"{type(exc).__name__}: {exc}"))
    finally:
        # SECRET HYGIENE is asserted regardless of whether the rest of the
        # spike succeeded, then the temp dir is shredded unconditionally.
        stdio_so_far = "\n".join(f"{r.name}: {'PASS' if r.passed else 'FAIL'} - {r.detail}" for r in results)
        results.append(assert_no_secret_leak(secret_values, stdio_so_far))
        shutil.rmtree(temp_dir, ignore_errors=True)

    print("Pairing/transport-security spike (Task 0.5) — disposable, see THREAT-MODEL.md\n")
    all_passed = True
    for result in results:
        status = "PASS" if result.passed else "FAIL"
        if not result.passed:
            all_passed = False
        print(f"[{status}] {result.name}: {result.detail}")

    print()
    if all_passed:
        print("ALL PROPERTIES PASSED. Ephemeral temp dir shredded. No secret material printed above.")
        return 0
    print("ONE OR MORE PROPERTIES FAILED. See detail lines above.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
