@dataclass
class FixtureAsset:
    """One media asset the manifest references, with its content hash."""

    asset_id: str
    content: bytes
    sha256: str = field(init=False)

    def __post_init__(self) -> None:
        self.sha256 = hashlib.sha256(self.content).hexdigest()


def build_fixture_manifest_and_asset() -> tuple[dict[str, Any], FixtureAsset]:
    """Build a minimal plain-JSON manifest + one asset, shaped like ``StationCore.get_manifest()``.

    Mirrors the read-surface shape in
    ``spikes/mac-substrate-2026-07-10/candidate_a/core.py:115-149`` (schema
    version, station revision, active entry summary with a media hash) —
    this spike does not import that module (YAGNI: no reducer wiring needed
    to prove transport-security properties), it only matches the JSON
    shape a real client would authenticate against.
    """
    asset = FixtureAsset(asset_id="entry-1-media", content=b"not real audio bytes, just a fixture payload")
    manifest = {
        "schema_version": 1,
        "station_revision": 1,
        "lifecycle": "playing",
        "active_entry": {
            "entry_id": "entry-1",
            "kind": "item",
            "media": {"asset_id": asset.asset_id, "sha256": asset.sha256, "byte_size": len(asset.content)},
        },
    }
    return manifest, asset


# ---------------------------------------------------------------------------
# Pairing/enrollment state (server-side, in-memory + ephemeral temp dir only)
# ---------------------------------------------------------------------------


class PairingStore:
    """Server-side pairing/enrollment state.

    All secret values (pairing token, per-client HMAC credentials) live
    only as attributes of this object (process memory) and are never
    written to any file under the repo. A "Keychain-shaped" ephemeral
    marker file is written under ``temp_dir`` purely to demonstrate where
    a real implementation would hand the credential to ``keyring``/the
    Keychain — see THREAT-MODEL.md's open-decision-#1 section. The login
    keychain is never touched.
    """

    def __init__(self, temp_dir: Path) -> None:
        self._temp_dir = temp_dir
        self._pairing_token = secrets.token_urlsafe(32)
        self._token_consumed = False
        self._lock = threading.Lock()
        # holder_id -> per-client HMAC credential (bytes)
        self._enrolled_clients: dict[str, bytes] = {}
        # seen (holder_id, nonce) pairs, for replay resistance on
        # authenticated requests (distinct from one-time *enrollment*)
        self._seen_nonces: set[tuple[str, str]] = set()

    @property
    def pairing_token(self) -> str:
        """The single-use enrollment token. Test-driver-only access; never logged/printed."""
        return self._pairing_token

    def enroll(self, presented_token: str, holder_id: str) -> bytes | None:
        """Attempt one-time enrollment.

        Returns the newly issued per-client HMAC credential on success, or
        None if the token is wrong or has already been consumed (by this
        or any other holder_id — the token is single-use *globally*, not
        per-client, matching "a pairing token cannot enroll twice").
        """
        with self._lock:
            if self._token_consumed:
                return None
            if not hmac.compare_digest(presented_token, self._pairing_token):
                return None
            credential = secrets.token_bytes(32)
            self._enrolled_clients[holder_id] = credential
            self._token_consumed = True
            # Demonstrate "Keychain-shaped" ephemeral custody: a real
            # implementation hands `credential` to `keyring.set_password(...)`
            # here instead of writing a marker file. We write only a
            # non-secret marker (holder_id, no credential bytes) so the
            # temp-dir listing has *something* to shred, without ever
            # putting the credential itself on disk anywhere, including
            # under the ephemeral dir.
            marker = self._temp_dir / f"enrolled-{holder_id}.marker"
            marker.write_text("enrolled (credential held only in process memory, not on disk)\n")
            return credential

    def credential_for(self, holder_id: str) -> bytes | None:
        return self._enrolled_clients.get(holder_id)

    def nonce_seen(self, holder_id: str, nonce: str) -> bool:
        """Return True if ``(holder_id, nonce)`` has already been recorded.

        Non-mutating: callers must not treat a False result as permission
        to skip calling :meth:`record_nonce` — the two are split
        deliberately so a request can be checked for replay *and* have its
        signature verified before the nonce is burned (see
        ``_authenticate``: recording a nonce for a request that turns out
        to have a bad signature would let an attacker who never had the
        credential burn nonces the legitimate client would otherwise use).
        """
        with self._lock:
            return (holder_id, nonce) in self._seen_nonces

    def record_nonce(self, holder_id: str, nonce: str) -> None:
        """Record ``(holder_id, nonce)`` as seen, after signature verification succeeds."""
        with self._lock:
            self._seen_nonces.add((holder_id, nonce))

    def all_secret_values(self) -> list[str]:
        """Every secret string this store has ever generated, for hygiene scanning only.

        Used exclusively by ``assert_no_secret_leak`` in this spike's
        test driver — never printed, logged, or written anywhere else.
        """
        values = [self._pairing_token]
        for credential in self._enrolled_clients.values():
            values.append(credential.hex())
        return values


