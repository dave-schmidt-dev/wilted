#!/usr/bin/env python3
"""Disposable pairing/transport-security spike — Task 0.5 (MAC-SIDE).

**This is a disposable spike. It is not production code.** See
``THREAT-MODEL.md`` in this directory for the full threat model and the
open-decision-#1 analysis (native macOS companion vs. one approved Python
Keychain/TLS dependency) this spike is meant to inform.

Proves, end to end, against a real localhost TLS server:

1. **ONE-TIME ENROLLMENT** — a pairing token enrolls a client exactly once;
   a second enrollment attempt with the same token is rejected (replay /
   double-enroll defense).
2. **AUTHENTICATED TRANSPORT** — an unauthenticated client (no/garbage
   credential) cannot fetch the station manifest or any asset.
3. **STALE-REVISION REJECTION** — a request presenting an
   ``expected_revision`` behind the server's current revision is rejected
   before any state is read back, mirroring the idempotent-write contract
   already enforced by the committed reducer
   (``wilted.station.reducer.Checkpoint.expected_revision``).
4. **ASSET-HASH REJECTION** — a request presenting a tampered/wrong asset
   hash is rejected; no asset bytes are ever returned for a hash mismatch.
5. **SECRET HYGIENE** — nothing generated by this spike (pairing token,
   per-client HMAC credential, TLS private key) ever touches a file under
   the repository working tree, ever appears in captured stdout/stderr, or
   ever appears in the log stream. Everything sensitive lives only under
   one ``tempfile.mkdtemp()`` directory, which is shredded in ``finally``.

Design notes (see THREAT-MODEL.md for the full writeup):

- The TLS server certificate/key are generated **once**, for this run
  only, via the macOS-bundled ``openssl`` CLI (subprocess), writing
  directly into the ephemeral temp dir. This spike does not use
  ``cryptography`` or any other non-stdlib Python dependency — it proves
  the *protocol* properties without deciding open-decision #1's dependency
  question. If a future spike needs certificate extensions ``openssl``
  can't express conveniently, that is itself evidence for the
  ``cryptography`` side of that decision (noted in THREAT-MODEL.md).
- Client authentication is **application-layer** (HMAC over method + path
  + expected_revision + timestamp + nonce, keyed by a per-client secret
  issued at enrollment), not X.509 client certificates. TLS here provides
  confidentiality/server-authenticity and defeats passive LAN
  eavesdropping + naive MITM; the HMAC layer provides per-client
  authentication and replay resistance. See THREAT-MODEL.md's transport
  recommendation for why full mTLS is not attempted in this spike.
- Discovery (Bonjour/``_wilted._tcp``) is simulated by hardcoding
  ``localhost`` — no real mDNS stack is stood up (YAGNI per the task
  brief: "no real Bonjour/mDNS stack needed").
- Real Keychain storage is NOT exercised against the login keychain. See
  THREAT-MODEL.md's "Open decision #1" section for the documented
  ``keyring``-backed approach; this spike stores the per-client credential
  only in an in-memory dict and the ephemeral temp dir, standing in for
  "Keychain-shaped" storage without touching the actual OS keychain.

Usage:
    python spikes/pairing-security-2026-07-10/pairing_spike.py

Exits 0 with every property PASS; exits 1 (non-zero) if any property
fails. This script is a CLI entry point, not an importable library module,
so it prints status lines rather than logging (matches project convention:
"CLI commands can print") — but never prints secret material; see
``SECRET HYGIENE`` below and its enforcement in ``main()``.
"""

