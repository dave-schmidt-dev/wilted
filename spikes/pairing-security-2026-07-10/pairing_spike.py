def _sign(credential: bytes, method: str, path: str, expected_revision: int, timestamp: str, nonce: str) -> str:
    """Compute the HMAC-SHA256 signature a client attaches to an authenticated request."""
    message = f"{method}|{path}|{expected_revision}|{timestamp}|{nonce}".encode()
    return hmac.new(credential, message, hashlib.sha256).hexdigest()


class StationRequestHandler(BaseHTTPRequestHandler):
    """Minimal handler: POST /enroll, GET /manifest, GET /asset.

    ``server`` is a :class:`_StationHTTPServer`, which carries the shared
    ``PairingStore`` and fixture manifest/asset.
    """

    server: _StationHTTPServer  # type: ignore[assignment]

    def log_message(self, format: str, *args: Any) -> None:  # noqa: A002
        """Suppress BaseHTTPRequestHandler's default stderr access log.

        The default implementation prints request lines (including the
        full path, which carries the HMAC signature and nonce — not the
        credential itself, but still request material we don't want on
        stdout/stderr per the "print no secret material" requirement).
        This spike's driver captures pass/fail via return values, not log
        scraping, so suppressing this is safe and correct.
        """

    def _send_json(self, status: int, payload: dict[str, Any] | None) -> None:
        body = json.dumps(payload).encode() if payload is not None else b""
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        if body:
            self.wfile.write(body)

    def _authenticate(self) -> str | None:
        """Return the authenticated holder_id, or None if auth fails.

        Expects headers ``X-Holder-Id``, ``X-Timestamp``, ``X-Nonce``,
        ``X-Signature``. Rejects: unknown holder, non-finite/stale
        timestamp, replayed nonce, or bad signature. Timestamp freshness
        (+/- 30s) additionally bounds replay of an
        intercepted-but-not-yet-used request.

        Order matters here: the nonce is only *recorded* (burned) after
        the HMAC signature has been verified. Checking-without-recording
        happens earlier so a replayed nonce is still rejected even with a
        valid signature, but a request with an invalid signature can never
        consume/burn a nonce the legitimate client would otherwise need —
        otherwise an on-path attacker who merely knows an enrolled
        ``holder_id`` (not secret) could DoS the nonce namespace with
        garbage signatures.
        """
        holder_id = self.headers.get("X-Holder-Id", "")
        timestamp = self.headers.get("X-Timestamp", "")
        nonce = self.headers.get("X-Nonce", "")
        signature = self.headers.get("X-Signature", "")
        if not (holder_id and timestamp and nonce and signature):
            return None
        credential = self.server.pairing_store.credential_for(holder_id)
        if credential is None:
            return None
        try:
            ts = float(timestamp)
        except ValueError:
            return None
        if not math.isfinite(ts) or abs(time.time() - ts) > 30:
            return None
        if self.server.pairing_store.nonce_seen(holder_id, nonce):
            return None
        expected_revision = self.headers.get("X-Expected-Revision", "-1")
        expected_signature = _sign(credential, self.command, self.path, int(expected_revision), timestamp, nonce)
        if not hmac.compare_digest(signature, expected_signature):
            return None
        self.server.pairing_store.record_nonce(holder_id, nonce)
        return holder_id

    def do_POST(self) -> None:  # noqa: N802
        if self.path == "/enroll":
            length = int(self.headers.get("Content-Length", "0"))
            raw = self.rfile.read(length) if length else b"{}"
            try:
                payload = json.loads(raw)
            except json.JSONDecodeError:
                self._send_json(400, {"error": "bad_request"})
                return
            presented_token = payload.get("token", "")
            holder_id = payload.get("holder_id", "")
            if not presented_token or not holder_id:
                self._send_json(400, {"error": "bad_request"})
                return
            credential = self.server.pairing_store.enroll(presented_token, holder_id)
            if credential is None:
                self._send_json(403, {"error": "enrollment_rejected"})
                return
            # The credential is returned exactly once, over TLS, to the
            # enrolling client only — this is the one point in the whole
            # protocol where it crosses the wire. It is never logged,
            # never printed, and the response body is not written to any
            # file by either side of this spike.
            self._send_json(200, {"credential_hex": credential.hex()})
            return
        self._send_json(404, {"error": "not_found"})

    def do_GET(self) -> None:  # noqa: N802
        holder_id = self._authenticate()
        if holder_id is None:
            self._send_json(403, None)  # No manifest, no asset, no body at all.
            return

        if self.path.startswith("/manifest"):
            query_revision = _query_param(self.path, "expected_revision")
            if query_revision is not None and int(query_revision) < self.server.manifest["station_revision"]:
                self._send_json(409, {"error": "stale_revision"})
                return
            self._send_json(200, self.server.manifest)
            return

        if self.path.startswith("/asset"):
            expected_hash = _query_param(self.path, "expected_sha256")
            if expected_hash is None or not hmac.compare_digest(expected_hash, self.server.asset.sha256):
                self._send_json(409, {"error": "asset_hash_mismatch"})
                return
            self.send_response(200)
            self.send_header("Content-Type", "application/octet-stream")
            self.send_header("Content-Length", str(len(self.server.asset.content)))
            self.end_headers()
            self.wfile.write(self.server.asset.content)
            return

        self._send_json(404, {"error": "not_found"})


def _query_param(path: str, name: str) -> str | None:
    if "?" not in path:
        return None
    _, _, query = path.partition("?")
    for part in query.split("&"):
        key, _, value = part.partition("=")
        if key == name:
            return value
    return None


class _StationHTTPServer(HTTPServer):
    """HTTPServer subclass carrying the shared pairing store + fixture data."""

    def __init__(self, address: tuple[str, int], pairing_store: PairingStore, manifest: dict, asset: FixtureAsset):
        super().__init__(address, StationRequestHandler)
        self.pairing_store = pairing_store
        self.manifest = manifest
        self.asset = asset


