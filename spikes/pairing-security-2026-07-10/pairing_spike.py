# ---------------------------------------------------------------------------
# Ephemeral TLS identity generation (openssl CLI, never a Python dependency)
# ---------------------------------------------------------------------------


def generate_ephemeral_tls_identity(temp_dir: Path) -> tuple[Path, Path]:
    """Generate a self-signed cert/key pair into ``temp_dir`` via ``openssl``.

    Uses the macOS-bundled ``openssl`` CLI so this spike adds zero Python
    dependencies. The key/cert are written only under ``temp_dir`` (never
    under the repo) and are the caller's responsibility to shred.

    Args:
        temp_dir: Ephemeral directory to write ``server.key``/``server.crt``
            into. Must already exist.

    Returns:
        ``(key_path, cert_path)``.

    Raises:
        RuntimeError: If the ``openssl`` subprocess fails or is not found.
    """
    key_path = temp_dir / "server.key"
    cert_path = temp_dir / "server.crt"
    try:
        subprocess.run(
            [
                "openssl",
                "req",
                "-x509",
                "-newkey",
                "ec",
                "-pkeyopt",
                "ec_paramgen_curve:prime256v1",
                "-keyout",
                str(key_path),
                "-out",
                str(cert_path),
                "-days",
                "1",
                "-nodes",
                "-subj",
                "/CN=wilted-station-spike.local",
            ],
            check=True,
            capture_output=True,
            timeout=30,
        )
    except FileNotFoundError as exc:
        raise RuntimeError("openssl CLI not found; required to generate the ephemeral TLS identity") from exc
    except subprocess.CalledProcessError as exc:
        # Deliberately do not include exc.stdout/exc.stderr verbatim in any
        # exception message that might get logged/printed — openssl error
        # output does not contain key material for a *failed* keygen, but
        # we keep this defensive per the "print no secret material, ever"
        # requirement.
        raise RuntimeError(f"openssl cert generation failed (exit {exc.returncode})") from exc
    if not key_path.exists() or not cert_path.exists():
        raise RuntimeError("openssl did not produce the expected key/cert files")
    return key_path, cert_path


